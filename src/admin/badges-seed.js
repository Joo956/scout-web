const CUSTOM_CATEGORIES_KEY = "ava-badge-categories";

export function loadCustomBadgeCategories() {
  try {
    const arr = JSON.parse(localStorage.getItem(CUSTOM_CATEGORIES_KEY) ?? "[]");
    return Array.isArray(arr) ? arr.filter((c) => typeof c === "string" && c.trim()) : [];
  } catch {
    return [];
  }
}

export function saveCustomBadgeCategory(name) {
  const clean = String(name ?? "").trim();
  if (!clean) return loadCustomBadgeCategories();
  const custom = loadCustomBadgeCategories();
  if (!custom.includes(clean) && !BADGE_CATEGORIES.includes(clean)) {
    custom.push(clean);
    try { localStorage.setItem(CUSTOM_CATEGORIES_KEY, JSON.stringify(custom)); } catch {}
  }
  return custom;
}

